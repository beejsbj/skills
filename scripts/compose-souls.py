#!/usr/bin/env python3
"""Compose Markdown souls from souls/composition.json using only the stdlib."""

import argparse
import json
import os
from pathlib import Path
import stat
import sys
import tempfile


HEADER = "<!-- Generated by scripts/compose-souls.py from souls/composition.json. -->"


def inside(root, value):
    if not isinstance(value, str) or not value.strip():
        raise ValueError("paths must be nonempty strings")
    path = Path(value)
    if path.is_absolute():
        raise ValueError(f"path must be relative to souls: {value}")
    resolved = (root / path).resolve()
    if not resolved.is_relative_to(root) or resolved == root:
        raise ValueError(f"path escapes souls or names its root: {value}")
    return resolved


def render(root, target=None):
    """Validate the whole manifest, then read every selected source before writing."""
    root = Path(root).resolve()
    manifest = inside(root, "composition.json")
    data = json.loads(manifest.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or type(data.get("version")) is not int or data["version"] != 1:
        raise ValueError("manifest version must be 1")
    targets = data.get("targets")
    if not isinstance(targets, dict) or not targets:
        raise ValueError("targets must be a nonempty object")
    validated = {}
    outputs, inputs = set(), {manifest}
    for name, spec in targets.items():
        if not isinstance(name, str) or not name.strip():
            raise ValueError("target names must be nonempty")
        if not isinstance(spec, dict):
            raise ValueError(f"invalid target: {name}")
        output = inside(root, spec.get("output"))
        parts = spec.get("parts")
        if not isinstance(parts, list) or not parts:
            raise ValueError(f"target {name} needs nonempty parts")
        sources = [inside(root, part) for part in parts]
        if output in outputs:
            raise ValueError(f"duplicate output: {output}")
        outputs.add(output)
        inputs.update(sources)
        validated[name] = (output, sources)
    if outputs & inputs:
        raise ValueError("outputs must not overlap input paths")
    if target is not None and target not in validated:
        raise ValueError(f"unknown target: {target}")
    rendered = []
    for name, (output, sources) in validated.items():
        if target is not None and name != target:
            continue
        parts = [source.read_text(encoding="utf-8").strip() for source in sources]
        if any(not part for part in parts):
            raise ValueError(f"target {name} has an empty source")
        rendered.append((output, ("\n\n".join([HEADER, *parts]) + "\n").encode("utf-8")))
    return rendered


def atomic_write(root, output, content):
    # Recheck containment before creating directories or replacing a destination.
    output = inside(root, str(output.relative_to(root)))
    output.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(output.stat().st_mode) if output.exists() else 0o644
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=output.parent, prefix=f".{output.name}.", delete=False) as handle:
            temporary = Path(handle.name)
            handle.write(content)
            handle.flush()
            os.fchmod(handle.fileno(), mode)
        os.replace(temporary, output)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--souls-dir", type=Path, default=Path(__file__).resolve().parents[1] / "souls")
    parser.add_argument("--target", help="compose only this manifest target (default: all)")
    parser.add_argument("--check", action="store_true", help="report missing or stale outputs without writing")
    args = parser.parse_args(argv)
    try:
        root = args.souls_dir.resolve()
        rendered = render(root, args.target)
        if args.check:
            stale = [path for path, content in rendered if not path.exists() or path.read_bytes() != content]
            for path in stale:
                print(f"stale or missing: {path}", file=sys.stderr)
            return int(bool(stale))
        for output, content in rendered:
            atomic_write(root, output, content)
        return 0
    except (OSError, ValueError, RuntimeError) as error:
        print(f"compose-souls: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
